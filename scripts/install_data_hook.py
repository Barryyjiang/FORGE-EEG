"""Install a ``sitecustomize`` hook so the data redirect applies to EVERY
process using this virtualenv, not just ones that import ``eegbench`` first.

Why this is needed: ``eegbench.paths.configure_data_home()`` only runs when
``eegbench`` is imported. Any script that goes straight to ``moabb``/``mne``
(including MOABB's own internals and notebook kernels that restart) would
otherwise fall back to ``~/mne_data`` and scatter data outside the project.

``sitecustomize`` is imported automatically at interpreter startup, before user
code, which closes that gap.

Run after creating or rebuilding the venv::

    .\\.venv\\Scripts\\python.exe scripts\\install_data_hook.py
"""

from __future__ import annotations

import sys
from pathlib import Path

from eegbench.paths import (
    MOABB_CACHE_DIR,
    MNE_DATA_DIR,
    MNE_HOME_DIR,
    OPT_OUT_ENV,
    PROJECT_ROOT,
)

TEMPLATE = r'''r"""Auto-generated by scripts/install_data_hook.py -- do not edit by hand.

Keeps MNE/MOABB downloads and caches inside {root}
for every Python process using this virtualenv. Regenerate with:

    .\.venv\Scripts\python.exe scripts\install_data_hook.py

Opt out for one shell with: set {opt_out}=1
"""

import os

if os.environ.get({opt_out!r}) != "1":
    os.environ["MNE_DATA"] = {mne_data!r}
    os.environ["MOABB_RESULTS"] = {moabb!r}
    os.environ["_MNE_FAKE_HOME_DIR"] = {mne_home!r}
'''


def main() -> int:
    site_packages = Path(sys.prefix) / "Lib" / "site-packages"
    if not site_packages.is_dir():  # non-Windows layout
        candidates = [Path(p) for p in sys.path if p.endswith("site-packages")]
        if not candidates:
            print("Could not locate site-packages", file=sys.stderr)
            return 1
        site_packages = candidates[0]

    target = site_packages / "sitecustomize.py"
    if target.exists():
        existing = target.read_text(encoding="utf-8")
        if "Auto-generated by scripts/install_data_hook.py" not in existing:
            print(f"REFUSING: {target} exists and was not generated by us.",
                  file=sys.stderr)
            return 1

    target.write_text(
        TEMPLATE.format(
            root=PROJECT_ROOT,
            opt_out=OPT_OUT_ENV,
            mne_data=str(MNE_DATA_DIR),
            moabb=str(MOABB_CACHE_DIR),
            mne_home=str(MNE_HOME_DIR),
        ),
        encoding="utf-8",
    )
    print(f"wrote {target}")
    print("Verify in a fresh process that does NOT import eegbench:")
    print('  .\\.venv\\Scripts\\python.exe -c "import moabb; print(__import__(\'mne\').get_config(\'MNE_DATA\'))"')
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
