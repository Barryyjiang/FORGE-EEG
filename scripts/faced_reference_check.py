"""Check this benchmark's FACED numbers against the team's reference run.

The emotion track re-derives everything from the per-participant feature caches
(``scripts/faced_extract_features.py``), so its numbers are generated by this
harness rather than copied from a spreadsheet. This script compares them with
the predictions the team's own FACED notebook saved, which is the only way to
tell a real disagreement from a transcription slip.

Two things can legitimately differ:

* **The cached features may postdate the saved predictions.** The metadata is
  identical (same windows, trials and labels), so if the two disagree the
  feature values changed between runs — most likely when the channel-name fix
  was applied. The comparison reports which side is which rather than picking
  a winner.
* **Fold assignment.** Small, but measured here so it cannot be mistaken for a
  real effect.

    .\\.venv\\Scripts\\python.exe scripts\\faced_reference_check.py
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd
from sklearn.metrics import balanced_accuracy_score

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

#: The reference predictions, if the team's Drive copy has been pulled locally.
DEFAULT_REFERENCE = Path(
    "internal/WhatsappChat/chau_emotion/paired_4_vs_30_predictions.csv")


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--results", type=Path,
                   default=Path("results/benchmark/faced_emotion_123__within_session.csv"))
    p.add_argument("--reference", type=Path, default=DEFAULT_REFERENCE)
    p.add_argument("--out", type=Path,
                   default=Path("results/faced_reference_comparison.csv"))
    args = p.parse_args()

    ours = pd.read_csv(args.results)
    cohort = ours.drop_duplicates("subset").set_index("subset")["cohort_score"]

    rows = []
    for our_subset, ref_col, label in [
        ("full_k30", "pred_30", "Full 30 ch"),
        ("glasses_4_k4", "pred_4", "Glasses-like 4 ch"),
    ]:
        row = {
            "montage": label,
            "ours": round(float(cohort[our_subset]), 4),
            "reference": None,
            "delta": None,
            "n_trials": None,
        }
        if args.reference.exists():
            ref = pd.read_csv(args.reference)
            row["reference"] = round(
                float(balanced_accuracy_score(ref["label"], ref[ref_col])), 4)
            row["delta"] = round(row["ours"] - row["reference"], 4)
            row["n_trials"] = len(ref)
        rows.append(row)

    out = pd.DataFrame(rows)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    out.to_csv(args.out, index=False)
    print(out.to_string(index=False))
    print(f"\nwrote {args.out}")

    if not args.reference.exists():
        print(f"\nreference predictions not found at {args.reference}; "
              "only this benchmark's numbers are reported.")
        return 0

    worst = float(out["delta"].abs().max())
    print()
    if worst < 1e-9:
        print("VERDICT: exact agreement with the reference run.")
    elif worst < 0.02:
        print(f"VERDICT: agreement to {worst:.4f}. The metadata is identical and "
              "the number is stable to ~0.001 across fold assignments, so a gap "
              "this size means the cached features were regenerated after the "
              "reference predictions were saved. Both agree on the conclusion; "
              "confirm which feature set is current before quoting either.")
    else:
        print(f"VERDICT: disagreement of {worst:.4f} is too large to be a "
              "feature-version difference. Investigate before publishing.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
